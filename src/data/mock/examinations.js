export function getGradeFromScore(obtained, max = 100) {
  if (max <= 0) return { grade: "F", gpa: 0.0, status: "Failed", percentage: 0 };
  const percentage = Math.round((obtained / max) * 100 * 10) / 10;

  for (const item of mockGradingScale) {
    if (percentage >= item.minScore && percentage <= item.maxScore) {
      return {
        grade: item.grade,
        gpa: item.gpa,
        status: item.grade === "F" ? "Failed" : "Passed",
        percentage,
        remarks: item.remarks,
        color: item.color,
      };
    }
  }
  return { grade: "F", gpa: 0.0, status: "Failed", percentage, remarks: "Remedial Required", color: "rose" };
}

